// plan 8.3 / 9 M1: sha256 of the protocol files, printed as the docs/FREEZE.md table.
// Usage: `npm run hash-protocol` prints; `npm run hash-protocol -- --write` also writes docs/FREEZE.md.
// Hashes raw file bytes, so each value equals `sha256sum <file>` on the same bytes. The set hash equals
// `sha256sum <files in PROTOCOL_FILES order> | sha256sum` (lines `<hex>  <path>\n`).
// Uses node:crypto and node:fs only; reads nothing outside the repo.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

/** Protocol files hashed into the freeze, repo-relative POSIX paths, in table order. */
export const PROTOCOL_FILES: readonly string[] = [
  'docs/FAMILIES.md',
  'docs/TRAPS.md',
  'docs/METRICS.md',
  'docs/ATOMS.md',
  'docs/POLICY.md',
  'docs/PREREGISTRATION.md',
  'docs/DATA.md',
  'policy.json',
  'schemas/change.schema.json',
  'schemas/corpus-manifest.schema.json',
  'schemas/label.schema.json',
  'schemas/placement.schema.json',
  'schemas/policy.schema.json',
  'schemas/prereg.schema.json',
  'schemas/receipt.schema.json',
  'schemas/results.schema.json',
  'src/corpus/contract.ts',
];

export const FREEZE_DOC = 'docs/FREEZE.md';

export interface ProtocolFileHash {
  path: string;
  /** sha256 hex of the raw bytes, or null when the file is missing. */
  sha256: string | null;
  bytes: number | null;
}

export interface ProtocolHashReport {
  files: ProtocolFileHash[];
  /** schemas/*.json present on disk but absent from PROTOCOL_FILES (must be empty). */
  unlistedSchemas: string[];
  /** sha256 of the `sha256sum`-format lines of all files; null when any file is missing. */
  setSha256: string | null;
}

export function sha256Hex(data: Uint8Array | string): string {
  return createHash('sha256').update(data).digest('hex');
}

/** Hash every protocol file under `root` (a directory URL ending in '/'). */
export function hashProtocolFiles(root: URL): ProtocolHashReport {
  const files: ProtocolFileHash[] = PROTOCOL_FILES.map((path) => {
    const url = new URL(path, root);
    if (!existsSync(url)) return { path, sha256: null, bytes: null };
    const bytes = readFileSync(url);
    return { path, sha256: sha256Hex(bytes), bytes: bytes.length };
  });

  const schemasDir = new URL('schemas/', root);
  const listed = new Set(PROTOCOL_FILES);
  const unlistedSchemas = existsSync(schemasDir)
    ? readdirSync(schemasDir)
        .filter((name) => name.endsWith('.json'))
        .map((name) => `schemas/${name}`)
        .filter((path) => !listed.has(path))
        .sort()
    : [];

  const complete = files.every((f) => f.sha256 !== null);
  const setSha256 = complete ? sha256Hex(files.map((f) => `${f.sha256}  ${f.path}\n`).join('')) : null;
  return { files, unlistedSchemas, setSha256 };
}

/** Render the docs/FREEZE.md text (LF line endings). */
export function renderFreezeDoc(report: ProtocolHashReport): string {
  const lines: string[] = [
    '# Protocol freeze hashes',
    '',
    'Status: **DRAFT**. Generated by `npm run hash-protocol -- --write`; recomputed by `scripts/freeze.ts` at the',
    'freeze (plan 8.3). Values are sha256 of the raw file bytes, lowercase hex, identical to `sha256sum <file>`.',
    'Line endings matter: hash the bytes as committed (LF), not a CRLF checkout.',
    '',
    '| File | sha256 | Bytes |',
    '|---|---|---|',
  ];
  for (const f of report.files) {
    lines.push(`| \`${f.path}\` | ${f.sha256 === null ? 'MISSING' : `\`${f.sha256}\``} | ${f.bytes ?? ''} |`);
  }
  lines.push('');
  lines.push(
    `Set hash (\`sha256sum\` lines of the files above, in this order, hashed again): ${
      report.setSha256 === null ? 'not computable (missing files)' : `\`${report.setSha256}\``
    }`,
  );
  lines.push('');
  return lines.join('\n');
}

function main(argv: readonly string[]): number {
  const write = argv.includes('--write');
  const root = new URL('../', import.meta.url);
  const report = hashProtocolFiles(root);
  const text = renderFreezeDoc(report);
  process.stdout.write(text);

  const missing = report.files.filter((f) => f.sha256 === null).map((f) => f.path);
  if (missing.length > 0) {
    process.stderr.write(`hash-protocol: missing protocol files: ${missing.join(', ')}\n`);
  }
  if (report.unlistedSchemas.length > 0) {
    process.stderr.write(`hash-protocol: schemas not listed in PROTOCOL_FILES: ${report.unlistedSchemas.join(', ')}\n`);
  }
  if (missing.length > 0 || report.unlistedSchemas.length > 0) {
    if (write) process.stderr.write(`hash-protocol: refusing to write ${FREEZE_DOC}\n`);
    return 1;
  }
  if (write) {
    writeFileSync(new URL(FREEZE_DOC, root), text);
    process.stderr.write(`hash-protocol: wrote ${FREEZE_DOC}\n`);
  }
  return 0;
}

const invokedDirectly = /(^|[\\/])hash-protocol\.ts$/.test(process.argv[1] ?? '');
if (invokedDirectly) {
  process.exitCode = main(process.argv.slice(2));
}
